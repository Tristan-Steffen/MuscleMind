export interface Set {
  id?: number; // Optional because it will be generated by the database
  reps: number;
  weight: number;
  rest: number | null;
}

export interface Exercise {
  id?: number;
  name: string;
  description: string;
  createdAt: string;
  updatedAt: string;
}

export interface ExerciseInstance {
  id?: number;
  sets: Set[];
  exercise: {
    data: Exercise;
  };
  createdAt: string;
  updatedAt: string;
}

export interface Session {
  id?: number;
  name: string;
  description: string;
  date: string;
  isPreset: boolean;
  exercise_instances: {
    data: ExerciseInstance[];
  };
  createdAt: string;
  updatedAt: string;
}
